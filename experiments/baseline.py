"""Baseline discovery, loading, validation, and provenance."""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

from experiments.utils import read_json, relative_path, sha256_file


@dataclass(frozen=True)
class Baseline:
    """A validated reference fingerprint document."""

    path: Path
    raw: dict[str, Any]
    fingerprint: dict[str, Any]
    metadata: dict[str, Any]
    sha256: str

    @property
    def label(self) -> str:
        return self.path.stem

    def provenance(self, root: Path) -> dict[str, Any]:
        return {
            "path": relative_path(self.path, root),
            "sha256": self.sha256,
            "label": self.label,
            "collected_at": self.metadata.get("collected_at"),
            "tool": self.metadata.get("tool"),
        }


def default_baseline_path(root: Path) -> Path:
    """Return the repository convention for the real-browser baseline."""
    return root / "reports" / "fingerprint" / "fingerprint_real.json"


def resolve_baseline_path(root: Path, requested: Path | None) -> Path:
    """Resolve a CLI baseline path or use the repository default."""
    if requested is None:
        return default_baseline_path(root)
    return requested if requested.is_absolute() else root / requested


def load_baseline(path: Path) -> Baseline:
    """Load and validate a baseline generated by a fingerprint collector."""
    resolved = path.resolve()
    if not resolved.is_file():
        raise FileNotFoundError(f"Baseline fingerprint not found: {resolved}")
    raw = read_json(resolved)
    if not isinstance(raw, dict):
        raise ValueError("Baseline root must be a JSON object")
    fingerprint = raw.get("fingerprint", raw)
    if not isinstance(fingerprint, dict) or not fingerprint:
        raise ValueError("Baseline does not contain a non-empty fingerprint object")
    metadata = raw.get("_meta", {})
    if not isinstance(metadata, dict):
        metadata = {}
    return Baseline(
        path=resolved,
        raw=raw,
        fingerprint=fingerprint,
        metadata=metadata,
        sha256=sha256_file(resolved),
    )

